fn adapter_function(function: &Function) -> String {
    let name = typescript_name(&function.name);
    let bridge = bridge_name(function);
    match &function.kind {
        ExportKind::Function if function.abi == FunctionAbi::Scalar => {
            scalar_adapter(function, &name, &bridge)
        }
        ExportKind::Function => json_adapter(function, &name, &bridge),
        ExportKind::Stream { item } | ExportKind::Iterator { item } => {
            reactive_adapter(function, item, &name, &bridge)
        }
        ExportKind::Async { .. }
        | ExportKind::Callback { .. }
        | ExportKind::Object { .. }
        | ExportKind::Trait { .. } => unreachable!("unsupported export reached the adapter"),
    }
}

fn scalar_adapter(function: &Function, name: &str, bridge: &str) -> String {
    let parameters = function
        .parameters
        .iter()
        .map(|parameter| format!("{}: {}", parameter.name, ts_type(&parameter.ty)))
        .collect::<Vec<_>>()
        .join(", ");
    let arguments = function
        .parameters
        .iter()
        .map(|parameter| parameter.name.as_str())
        .collect::<Vec<_>>()
        .join(", ");
    if matches!(function.result, Type::Scalar(Scalar::Void)) {
        return format!(
            "export function {name}({parameters}): void {{\n  const __eqtsStatus = {bridge}({arguments});\n  checkStatus(__eqtsStatus, \"{}\");\n}}\n",
            function.name
        );
    }
    let result = ts_type(&function.result);
    let initial = if matches!(function.result, Type::Scalar(Scalar::Bool)) {
        "false"
    } else {
        "0"
    };
    let separator = if arguments.is_empty() { "" } else { ", " };
    format!(
        "export function {name}({parameters}): {result} {{\n  let __eqtsValue: {result} = {initial};\n  const __eqtsStatus = {bridge}({arguments}{separator}(value: {result}) => {{ __eqtsValue = value; }});\n  checkStatus(__eqtsStatus, \"{}\");\n  return __eqtsValue;\n}}\n",
        function.name
    )
}

fn json_adapter(function: &Function, name: &str, bridge: &str) -> String {
    let parameters = function
        .parameters
        .iter()
        .map(|parameter| format!("{}: {}", parameter.name, ts_type(&parameter.ty)))
        .collect::<Vec<_>>()
        .join(", ");
    let arguments = function
        .parameters
        .iter()
        .map(|parameter| scriptc_wire_encode(&parameter.name, &parameter.ty))
        .collect::<Vec<_>>()
        .join(", ");
    let status = format!(
        "  let __eqtsText = \"\";\n  const __eqtsStatus = {bridge}(JSON.stringify([{arguments}]), (data: Uint8Array) => {{ __eqtsText = __eqtsDecode(data); }});\n  checkStatus(__eqtsStatus, \"{}\", __eqtsText);\n",
        function.name
    );
    if matches!(function.result, Type::Scalar(Scalar::Void)) {
        return format!("export function {name}({parameters}): void {{\n{status}}}\n");
    }
    let result = ts_type(&function.result);
    let decode = match &function.result {
        Type::Owned(OwnedType::Result { ok, error }) => {
            let ok_cast = scriptc_cast_type(ok);
            let error_cast = scriptc_cast_type(error);
            let error_value = if matches!(**error, Type::Owned(OwnedType::String)) {
                "__eqtsDecoded.error".to_string()
            } else {
                format!(
                    "JSON.stringify({})",
                    scriptc_wire_decode("__eqtsDecoded.error", error)
                )
            };
            format!(
                "  const __eqtsDecoded = JSON.parse(__eqtsText) as {{ ok: {ok_cast} }} | {{ error: {error_cast} }};\n  if (\"error\" in __eqtsDecoded) throw new EqtsError(\"RUST_ERROR\", {error_value});\n  return {};\n",
                scriptc_wire_decode("__eqtsDecoded.ok", ok)
            )
        }
        ty => format!(
            "  const __eqtsDecoded = JSON.parse(__eqtsText) as {};\n  return {};\n",
            scriptc_cast_type(ty),
            scriptc_wire_decode("__eqtsDecoded", ty)
        ),
    };
    format!("export function {name}({parameters}): {result} {{\n{status}{decode}}}\n")
}

fn reactive_adapter(function: &Function, item: &Type, name: &str, bridge: &str) -> String {
    let parameters = function
        .parameters
        .iter()
        .map(|parameter| format!("{}: {}", parameter.name, ts_type(&parameter.ty)))
        .collect::<Vec<_>>()
        .join(", ");
    let arguments = function
        .parameters
        .iter()
        .map(|parameter| scriptc_wire_encode(&parameter.name, &parameter.ty))
        .collect::<Vec<_>>()
        .join(", ");
    format!(
        "export function {name}({parameters}): EqtsHandle<{}> {{\n  let __eqtsHi = 0;\n  let __eqtsLo = 0;\n  const __eqtsStatus = {bridge}(JSON.stringify([{arguments}]), (hi: number, lo: number) => {{ __eqtsHi = hi; __eqtsLo = lo; }});\n  checkStatus(__eqtsStatus, \"{}\");\n  return new EqtsHandle<{}>(__eqtsHi, __eqtsLo);\n}}\n",
        ts_type(item),
        function.name,
        ts_type(item)
    )
}

/// The type a checked cast validates against: the wire shape, which differs from
/// the declared TypeScript type wherever JSON carries bytes as arrays or 64-bit
/// integers as strings.
fn scriptc_cast_type(ty: &Type) -> String {
    match ty {
        Type::Scalar(Scalar::U64 | Scalar::I64) => "string".to_string(),
        Type::Owned(OwnedType::Bytes) => "number[]".to_string(),
        Type::Owned(OwnedType::Vec { value }) => {
            format!("Array<{}>", scriptc_cast_type(value))
        }
        Type::Owned(OwnedType::Option { value }) => {
            format!("{} | null", scriptc_cast_type(value))
        }
        Type::Owned(OwnedType::Record { fields, .. }) => {
            let fields = fields
                .iter()
                .map(|field| format!("{}: {}", field.name, scriptc_cast_type(&field.ty)))
                .collect::<Vec<_>>()
                .join("; ");
            format!("{{ {fields} }}")
        }
        Type::Scalar(_) | Type::Owned(OwnedType::String | OwnedType::Enum { .. }) => ts_type(ty),
        Type::Owned(OwnedType::Result { ok, .. }) => scriptc_cast_type(ok),
    }
}
