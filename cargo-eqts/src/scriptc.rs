//! scriptc transport generation.
//!
//! [scriptc](https://scriptc.dev) compiles TypeScript into a self-contained
//! native executable and links native code through a manifest-declared C ABI
//! surface. That surface is narrower than the shared eqts C ABI: it has no
//! 64-bit integer class, no pointer parameters, no owned pointer returns, and no
//! runtime symbol lookup. This module therefore emits three artifacts beside the
//! crate's static library:
//!
//! - `eqts_shim.c` adapts the status-and-out-pointer ABI to the classes scriptc
//!   can express, delivering results through call-scoped callbacks and carrying
//!   `u64` handles as a high/low `u32` pair.
//! - `ffi.json` binds the bridge and the crate's static library at link time.
//! - `index.ts` exposes the same camelCase API as the other transports with no
//!   runtime library loading.
//!
//! The generated `index.ts` is scriptc-only. Its `declare function`
//! declarations emit no JavaScript, so the module cannot run under Node, Bun,
//! or Deno.

