/// The scalar classes scriptc's FFI can carry. `u16`, `u64`, `i8`, `i16`, `i64`,
/// and `f32` have no equivalent class.
fn supported_scalar(scalar: Scalar) -> bool {
    matches!(
        scalar,
        Scalar::Void | Scalar::Bool | Scalar::U8 | Scalar::U32 | Scalar::I32 | Scalar::F64
    )
}

fn scalar_name(scalar: Scalar) -> &'static str {
    match scalar {
        Scalar::Void => "void",
        Scalar::Bool => "bool",
        Scalar::U8 => "u8",
        Scalar::U16 => "u16",
        Scalar::U32 => "u32",
        Scalar::U64 => "u64",
        Scalar::I8 => "i8",
        Scalar::I16 => "i16",
        Scalar::I32 => "i32",
        Scalar::I64 => "i64",
        Scalar::F32 => "f32",
        Scalar::F64 => "f64",
    }
}

/// The scriptc manifest class for a scalar.
fn abi_class(scalar: Scalar) -> &'static str {
    match scalar {
        Scalar::Bool => "bool",
        Scalar::U8 => "u8",
        Scalar::U32 => "u32",
        Scalar::I32 => "i32",
        Scalar::F64 => "f64",
        _ => unreachable!("unsupported scalar reached scriptc code generation"),
    }
}

/// The generated TypeScript declaration name for one export.
fn bridge_name(function: &Function) -> String {
    let mut name = typescript_name(&function.name);
    if let Some(first) = name.chars().next() {
        name.replace_range(..first.len_utf8(), &first.to_uppercase().to_string());
    }
    format!("eqtsSc{name}")
}

/// The generated C symbol for one export.
fn bridge_symbol(function: &Function) -> String {
    format!("eqts_sc_{}", function.name)
}

/// Reject exports the scriptc target cannot express, before any work is done.
pub(crate) fn validate(functions: &[Function]) -> Result<()> {
    for function in functions {
        if RESERVED_NAMES.contains(&function.name.as_str()) {
            bail!(
                "export `{}` collides with a reserved scriptc bridge name; rename it to build this target",
                function.name
            );
        }
        match &function.kind {
            ExportKind::Function => {
                if function.abi == FunctionAbi::Scalar {
                    for parameter in &function.parameters {
                        require_scalar(function, &parameter.ty, "parameter")?;
                    }
                    require_scalar(function, &function.result, "result")?;
                }
            }
            ExportKind::Stream { item } | ExportKind::Iterator { item } => {
                require_plain(function, item, "item")?;
            }
            ExportKind::Async { .. } => bail!(
                "export `{}` is asynchronous; the scriptc target supports synchronous functions, streams, and iterators only",
                function.name
            ),
            ExportKind::Callback { .. } => bail!(
                "export `{}` is a callback export; the scriptc target supports synchronous functions, streams, and iterators only",
                function.name
            ),
            ExportKind::Object { .. } | ExportKind::Trait { .. } => bail!(
                "export `{}` is a stateful proxy; the scriptc target supports synchronous functions, streams, and iterators only",
                function.name
            ),
        }
    }
    Ok(())
}

fn require_scalar(function: &Function, ty: &Type, role: &str) -> Result<()> {
    let scalar = scalar_type(ty);
    if supported_scalar(scalar) {
        return Ok(());
    }
    bail!(
        "export `{}` has a {role} of type {}, which the scriptc FFI cannot carry; scriptc accepts void, bool, u8, u32, i32, and f64 only",
        function.name,
        scalar_name(scalar)
    )
}

fn require_plain(function: &Function, ty: &Type, role: &str) -> Result<()> {
    if matches!(ty, Type::Owned(OwnedType::Result { .. })) {
        bail!(
            "export `{}` has a {role} of type Result, which has no single TypeScript shape; return the ok type and let a Rust error become an EqtsError",
            function.name
        );
    }
    Ok(())
}

/// Render the C bridge that adapts eqts's shared ABI to scriptc's classes.
pub(crate) fn render_shim(functions: &[Function]) -> String {
    let mut output = String::from(
        "/* Generated by cargo-eqts for the scriptc transport. Do not edit. */\n\
         #include <stddef.h>\n\
         #include <stdint.h>\n\n\
         typedef struct {\n\
         \x20 uint8_t *ptr;\n\
         \x20 size_t len;\n\
         \x20 size_t capacity;\n\
         } EqtsOwnedBuffer;\n\n\
         extern void eqts_buffer_free_v1(uint8_t *ptr, size_t len, size_t capacity);\n\
         extern int32_t eqts_handle_dispose_v1(uint64_t handle);\n\
         extern int32_t eqts_reactive_cancel_v1(uint64_t handle);\n\
         extern int32_t eqts_reactive_poll_v1(uint64_t handle, EqtsOwnedBuffer *output);\n\n",
    );
    for function in functions {
        writeln!(output, "{}", extern_declaration(function))
            .expect("writing to a string cannot fail");
    }
    output.push_str(
        "\nint32_t eqts_sc_bridge_poll(uint32_t hi, uint32_t lo, void (*emit)(const uint8_t *, size_t)) {\n\
         \x20 EqtsOwnedBuffer output = {NULL, 0, 0};\n\
         \x20 int32_t status = eqts_reactive_poll_v1(((uint64_t)hi << 32) | (uint64_t)lo, &output);\n\
         \x20 if (output.ptr != NULL) {\n\
         \x20   if (emit != NULL) emit(output.ptr, output.len);\n\
         \x20   eqts_buffer_free_v1(output.ptr, output.len, output.capacity);\n\
         \x20 }\n\
         \x20 return status;\n\
         }\n\n\
         int32_t eqts_sc_bridge_cancel(uint32_t hi, uint32_t lo) {\n\
         \x20 return eqts_reactive_cancel_v1(((uint64_t)hi << 32) | (uint64_t)lo);\n\
         }\n\n\
         int32_t eqts_sc_bridge_dispose(uint32_t hi, uint32_t lo) {\n\
         \x20 return eqts_handle_dispose_v1(((uint64_t)hi << 32) | (uint64_t)lo);\n\
         }\n\n",
    );
    for function in functions {
        writeln!(output, "{}", bridge_function(function)).expect("writing to a string cannot fail");
    }
    output
}

fn extern_declaration(function: &Function) -> String {
    match &function.kind {
        ExportKind::Function if function.abi == FunctionAbi::Scalar => {
            let mut parameters = function
                .parameters
                .iter()
                .map(|parameter| {
                    format!("{} {}", c_type(scalar_type(&parameter.ty)), parameter.name)
                })
                .collect::<Vec<_>>();
            if !matches!(function.result, Type::Scalar(Scalar::Void)) {
                parameters.push(format!("{} *output", c_type(scalar_type(&function.result))));
            }
            format!(
                "extern int32_t {}({});",
                function.symbol,
                parameters.join(", ")
            )
        }
        ExportKind::Function => format!(
            "extern int32_t {}(const uint8_t *input, size_t len, EqtsOwnedBuffer *output);",
            function.symbol
        ),
        ExportKind::Stream { .. } | ExportKind::Iterator { .. } => format!(
            "extern int32_t {}(const uint8_t *input, size_t len, uint64_t *output);",
            function.symbol
        ),
        ExportKind::Async { .. }
        | ExportKind::Callback { .. }
        | ExportKind::Object { .. }
        | ExportKind::Trait { .. } => unreachable!("unsupported export reached the scriptc shim"),
    }
}

fn bridge_function(function: &Function) -> String {
    let symbol = bridge_symbol(function);
    match &function.kind {
        ExportKind::Function if function.abi == FunctionAbi::Scalar => {
            let parameters = function
                .parameters
                .iter()
                .map(|parameter| {
                    format!("{} {}", c_type(scalar_type(&parameter.ty)), parameter.name)
                })
                .collect::<Vec<_>>();
            let arguments = function
                .parameters
                .iter()
                .map(|parameter| parameter.name.as_str())
                .collect::<Vec<_>>()
                .join(", ");
            let separator = if arguments.is_empty() { "" } else { ", " };
            if matches!(function.result, Type::Scalar(Scalar::Void)) {
                let signature = if parameters.is_empty() {
                    "void".to_owned()
                } else {
                    parameters.join(", ")
                };
                return format!(
                    "int32_t {symbol}({signature}) {{\n  return {}({arguments});\n}}\n",
                    function.symbol
                );
            }
            let result = c_type(scalar_type(&function.result));
            let mut signature = parameters;
            signature.push(format!("void (*emit)({result})"));
            format!(
                "int32_t {symbol}({}) {{\n  {result} output = 0;\n  int32_t status = {}({arguments}{separator}&output);\n  if (status == 0 && emit != NULL) emit(output);\n  return status;\n}}\n",
                signature.join(", "),
                function.symbol
            )
        }
        ExportKind::Function => format!(
            "int32_t {symbol}(const uint8_t *input, size_t len, void (*emit)(const uint8_t *, size_t)) {{\n  EqtsOwnedBuffer output = {{NULL, 0, 0}};\n  int32_t status = {}(input, len, &output);\n  if (output.ptr != NULL) {{\n    if (emit != NULL) emit(output.ptr, output.len);\n    eqts_buffer_free_v1(output.ptr, output.len, output.capacity);\n  }}\n  return status;\n}}\n",
            function.symbol
        ),
        ExportKind::Stream { .. } | ExportKind::Iterator { .. } => format!(
            "int32_t {symbol}(const uint8_t *input, size_t len, void (*emit)(uint32_t, uint32_t)) {{\n  uint64_t handle = 0;\n  int32_t status = {}(input, len, &handle);\n  if (status == 0 && emit != NULL) emit((uint32_t)(handle >> 32), (uint32_t)(handle & 0xffffffffu));\n  return status;\n}}\n",
            function.symbol
        ),
        ExportKind::Async { .. }
        | ExportKind::Callback { .. }
        | ExportKind::Object { .. }
        | ExportKind::Trait { .. } => unreachable!("unsupported export reached the scriptc shim"),
    }
}

/// Render the scriptc FFI manifest that links the bridge and the crate archive.
pub(crate) fn render_manifest(functions: &[Function], archive: &str, shim: &str) -> String {
    let mut entries = functions.iter().map(manifest_entry).collect::<Vec<_>>();
    entries.push(json!({
        "name": "eqtsScBridgePoll",
        "symbol": "eqts_sc_bridge_poll",
        "params": ["u32", "u32", callback_entry(&["bytes"])],
        "returns": "i32",
    }));
    entries.push(json!({
        "name": "eqtsScBridgeCancel",
        "symbol": "eqts_sc_bridge_cancel",
        "params": ["u32", "u32"],
        "returns": "i32",
    }));
    entries.push(json!({
        "name": "eqtsScBridgeDispose",
        "symbol": "eqts_sc_bridge_dispose",
        "params": ["u32", "u32"],
        "returns": "i32",
    }));
    let document = json!({
        "ffi_format": 3,
        "functions": entries,
        "libraries": [format!("./{shim}"), format!("./{archive}")],
        "system_libraries": system_libraries(),
    });
    let mut text =
        serde_json::to_string_pretty(&document).expect("manifest serialization cannot fail");
    text.push('\n');
    text
}

fn callback_entry(classes: &[&str]) -> Value {
    json!({
        "callback": {
            "id": "emit",
            "params": classes,
            "returns": "void",
            "lifetime": "call",
        }
    })
}

fn manifest_entry(function: &Function) -> Value {
    let name = bridge_name(function);
    let symbol = bridge_symbol(function);
    let (params, result) = match &function.kind {
        ExportKind::Function if function.abi == FunctionAbi::Scalar => {
            let mut params = function
                .parameters
                .iter()
                .map(|parameter| json!(abi_class(scalar_type(&parameter.ty))))
                .collect::<Vec<_>>();
            if !matches!(function.result, Type::Scalar(Scalar::Void)) {
                params.push(callback_entry(&[abi_class(scalar_type(&function.result))]));
            }
            (params, "i32")
        }
        ExportKind::Function => (vec![json!("string"), callback_entry(&["bytes"])], "i32"),
        ExportKind::Stream { .. } | ExportKind::Iterator { .. } => (
            vec![json!("string"), callback_entry(&["u32", "u32"])],
            "i32",
        ),
        ExportKind::Async { .. }
        | ExportKind::Callback { .. }
        | ExportKind::Object { .. }
        | ExportKind::Trait { .. } => unreachable!("unsupported export reached the manifest"),
    };
    json!({ "name": name, "symbol": symbol, "params": params, "returns": result })
}

fn system_libraries() -> Vec<&'static str> {
    if cfg!(target_os = "macos") {
        vec!["m"]
    } else {
        vec!["m", "dl", "pthread"]
    }
}

/// Render the TypeScript adapter that scriptc compiles into the executable.
pub(crate) fn render_adapter(functions: &[Function]) -> String {
    let mut output = String::from(
        "// Generated by cargo-eqts for the scriptc transport. Do not edit.\n\
         //\n\
         // These `declare function` declarations bind native symbols through\n\
         // `ffi.json` at link time. The module is scriptc-only: it has no\n\
         // runtime library loading and cannot run under Node, Bun, or Deno.\n\n",
    );
    output.push_str(&crate::type_definitions(functions));
    for function in functions {
        writeln!(output, "{}", adapter_declaration(function))
            .expect("writing to a string cannot fail");
    }
    output.push_str(
        "declare function eqtsScBridgePoll(hi: number, lo: number, emit: (data: Uint8Array) => void): number;\n\
         declare function eqtsScBridgeCancel(hi: number, lo: number): number;\n\
         declare function eqtsScBridgeDispose(hi: number, lo: number): number;\n\n",
    );
    output.push_str(ADAPTER_RUNTIME);
    for function in functions {
        writeln!(output, "{}", adapter_function(function))
            .expect("writing to a string cannot fail");
    }
    output
}

fn adapter_declaration(function: &Function) -> String {
    let name = bridge_name(function);
    match &function.kind {
        ExportKind::Function if function.abi == FunctionAbi::Scalar => {
            let mut parameters = function
                .parameters
                .iter()
                .map(|parameter| format!("{}: {}", parameter.name, ts_type(&parameter.ty)))
                .collect::<Vec<_>>();
            if !matches!(function.result, Type::Scalar(Scalar::Void)) {
                parameters.push(format!(
                    "emit: (value: {}) => void",
                    ts_type(&function.result)
                ));
            }
            format!(
                "declare function {name}({}): number;",
                parameters.join(", ")
            )
        }
        ExportKind::Function => format!(
            "declare function {name}(input: string, emit: (data: Uint8Array) => void): number;"
        ),
        ExportKind::Stream { .. } | ExportKind::Iterator { .. } => format!(
            "declare function {name}(input: string, emit: (hi: number, lo: number) => void): number;"
        ),
        ExportKind::Async { .. }
        | ExportKind::Callback { .. }
        | ExportKind::Object { .. }
        | ExportKind::Trait { .. } => unreachable!("unsupported export reached the adapter"),
    }
}

